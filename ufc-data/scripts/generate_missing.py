"""Generate plot data for UFC 3-340-02 figures that have no original .grf file
but can be computed exactly from the guide's own definitions.

  Figure 3-64        C1 = 1.000, C2 = 1.0 (single triangular pulse)
  Figures 3-220..224 C1 = 0.909, 0.866, 0.825, 0.787, 0.750; C2 = 1000
      Maximum response of an elasto-plastic SDOF system to a bilinear-triangular
      pulse (scripts/sdof_bilinear.py). Same layout as the neighbouring original
      files: panel A = tm/Tn, B = Xm/XE, C = tE/T; curves for P/ru = 0.5 ... 20;
      T/Tn from 0.001 to 10 on a log grid; curves stop where Xm/XE reaches 1000.
  Figure 6-21        Roof live load vs supported tributary area (guide section 6-21,
                     specification 4.2.1): 20 psf to 200 ft2, linear to 12 psf at
                     600 ft2, 12 psf beyond.

Checks (see reference/HANDOFF.md): the SDOF calculator reproduces original Figure 3-54
(triangular load, = C1 = C2 = 1) with median error 0.00%, and the neighbouring
original Figure 3-225 (C1 = 0.715, C2 = 1000) with median error 0.6% (ductility).

Output: DPLOT-style .grf files in graphs/generated/ (file names as the original set).
Usage:  python3 scripts/generate_missing.py --out graphs/generated
"""
import argparse, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sdof_bilinear import max_response  # noqa: E402

P_RU = [0.5, 0.7, 0.9, 1.0, 1.1, 1.25, 1.5, 2.0, 3.0, 5.0, 10.0, 20.0]
T_GRID = [10 ** (-3 + 0.08 * k) for k in range(51)]  # 0.001 ... 10, as the original files
CHARTS = {  # figure number: (C1, C2)
    '3-64': (1.000, 1.0),
    '3-220': (0.909, 1000.0), '3-221': (0.866, 1000.0), '3-222': (0.825, 1000.0),
    '3-223': (0.787, 1000.0), '3-224': (0.750, 1000.0),
}
PANELS = [('A', 'T{\\dmax} / T{\\dn}', 1), ('B', 'Y{\\dmax} / Y{\\delastic}', 0), ('C', 'T{\\dyield} / T{\\dd}', 2)]
NOTE = 'GENERATED by scripts/generate_missing.py (computed; not part of the original plot set)'


def write_grf(path, curves, text_lines):
    """curves: list of (label, [(x, y), ...]). DPLOT v1.6 'data' layout."""
    with open(path, 'w', newline='\r\n') as fh:
        fh.write('DPLOT v1.6\ndata\n%d\n' % len(curves))
        for label, pts in curves:
            fh.write('%d\n' % len(pts))
            for x, y in pts:
                fh.write('%.7g,%.7g\n' % (x, y))
            fh.write(' 1    0\n%s\n\n' % label)
        for t in text_lines:
            fh.write(t + '\n')


def fmt(p):
    return ('%g' % p) + ('.' if float(p).is_integer() else '')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    for fig, (C1, C2) in CHARTS.items():
        num = int(fig.split('-')[1])
        results = {p: [(T, max_response(p, T, C1, C2)) for T in T_GRID] for p in P_RU}
        for panel, ylabel, idx in PANELS:
            curves = []
            for p in P_RU:
                pts = []
                for T, (xm, tm, te) in results[p]:
                    if xm >= 1000.0:
                        if panel == 'B':
                            pts.append((T, 1000.0))
                        break
                    val = (xm, tm, te)[idx]  # idx: 0 = Xm/XE, 1 = tm/Tn, 2 = tE/T
                    if val is not None:
                        pts.append((T, val))
                if pts:
                    curves.append((fmt(p), pts))
            title = ['Figure %s%s.  Maximum response of elastoplastic, one-degree-of-freedom' % (fig, panel.lower()),
                     'system for bilinear triangular pulse, C{\\d1} = %.4f, C{\\d2} = %.3f' % (C1, C2),
                     'Load Duration to Fundamental Period, T/T{\\dn}', ylabel, NOTE]
            name = '03_%03d%s.GRF' % (num, panel)
            write_grf(os.path.join(a.out, name), curves, title)
            print('wrote', name, len(curves), 'curves')
    write_grf(os.path.join(a.out, '06_021.grf'),
              [('Roof live load', [(0, 20), (200, 20), (600, 12), (1000, 12)])],
              ['Figure 6-21.  Recommended pre-engineered building design loads: roof live load',
               'Supported tributary area, ft{\\u2}', 'Load, psf',
               'Floor live load 150 psf (constant). ' + NOTE])
    print('wrote 06_021.grf')


if __name__ == '__main__':
    main()
